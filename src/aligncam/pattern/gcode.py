"""G-code generator for the calibration pattern.

The output is a single-layer print that uses only standard G-code and Klipper
commands. Everything printer-specific (start/end sequence, tool change) is a
Jinja2 template taken from :class:`~aligncam.config.PrinterConfig`, because the
real U1 macros are TO VERIFY ON HARDWARE.
"""

from __future__ import annotations

import math
from collections.abc import Iterable

import numpy as np
from jinja2 import Environment, StrictUndefined

from aligncam import __version__
from aligncam.config import PrinterConfig
from aligncam.geometry import Layout, Path

MIN_TRAVEL_FOR_RETRACT_MM = 2.0

_env = Environment(undefined=StrictUndefined, keep_trailing_newline=True)


def _render(template: str, **ctx: object) -> str:
    out = _env.from_string(template).render(**ctx)
    return out if out.endswith("\n") else out + "\n"


def extrusion_per_mm(line_width: float, layer_height: float, printer: PrinterConfig) -> float:
    """Filament length per mm of path (Slic3r rounded-rectangle bead model)."""
    area = (line_width - layer_height) * layer_height + math.pi * (layer_height / 2.0) ** 2
    filament_area = math.pi * (printer.filament_diameter_mm / 2.0) ** 2
    return area / filament_area * printer.flow


def check_bounds(layout: Layout, printer: PrinterConfig) -> None:
    x0, y0, x1, y1 = layout.bed_bbox()
    lo, hi = (x0, y0), (x1, y1)
    bx, by = printer.bed_size_mm
    if lo[0] < 0 or lo[1] < 0 or hi[0] > bx or hi[1] > by:
        raise ValueError(
            f"pattern spans X {lo[0]:.1f}..{hi[0]:.1f}, Y {lo[1]:.1f}..{hi[1]:.1f} mm, "
            f"outside the configured bed {bx:.0f} x {by:.0f} mm"
        )


def _fmt(v: float) -> str:
    return f"{v:.3f}".rstrip("0").rstrip(".") if v != 0 else "0"


def _tool_moves(
    paths: Iterable[Path],
    layout: Layout,
    printer: PrinterConfig,
    start_xy: np.ndarray | None,
) -> tuple[list[str], np.ndarray | None]:
    cfg = layout.config
    z = cfg.layer_height_mm
    e_mm = extrusion_per_mm(cfg.line_width_mm, cfg.layer_height_mm, printer)
    f_print = printer.print_speed_mm_s * 60
    f_travel = printer.travel_speed_mm_s * 60
    f_retract = printer.retract_speed_mm_s * 60
    out: list[str] = []
    pos = start_xy
    retracted = False
    for path in paths:
        pts = layout.to_bed(np.array(path.points))
        travel = math.inf if pos is None else float(np.hypot(*(pts[0] - pos)))
        if travel > 1e-6:
            long_travel = travel >= MIN_TRAVEL_FOR_RETRACT_MM
            if long_travel and not retracted and printer.retract_mm > 0:
                out.append(f"G1 E-{_fmt(printer.retract_mm)} F{f_retract:.0f}")
                retracted = True
            if long_travel:
                out.append(f"G1 Z{_fmt(z + printer.z_hop_mm)} F{f_travel:.0f}")
            out.append(f"G0 X{_fmt(pts[0][0])} Y{_fmt(pts[0][1])} F{f_travel:.0f}")
            if long_travel:
                out.append(f"G1 Z{_fmt(z)} F{f_travel:.0f}")
        if retracted:
            out.append(f"G1 E{_fmt(printer.retract_mm)} F{f_retract:.0f}")
            retracted = False
        for a, b in zip(pts[:-1], pts[1:], strict=True):
            length = float(np.hypot(*(b - a)))
            out.append(f"G1 X{_fmt(b[0])} Y{_fmt(b[1])} E{length * e_mm:.5f} F{f_print:.0f}")
        pos = pts[-1]
    if printer.retract_mm > 0 and out:
        out.append(f"G1 E-{_fmt(printer.retract_mm)} F{f_retract:.0f}")
        out.append(f"G1 Z{_fmt(z + printer.z_hop_mm)} F{f_travel:.0f}")
    return out, pos


def generate_gcode(layout: Layout, printer: PrinterConfig | None = None) -> str:
    printer = printer or PrinterConfig()
    check_bounds(layout, printer)
    cfg = layout.config
    for tool in layout.print_order:
        if tool >= printer.tool_count:
            raise ValueError(f"tool T{tool} does not exist on a {printer.tool_count}-tool printer")

    lines = [
        f"; U1 AlignCam calibration pattern, generated by aligncam {__version__}",
        "; Single layer. Every tool prints its own gratings; T0 also prints the fiducials.",
        f"; pitch {cfg.pitch_mm} mm, vernier ratio {cfg.vernier_ratio}, "
        f"line width {cfg.line_width_mm} mm, layer {cfg.layer_height_mm} mm",
        f"; pattern centre on bed: X{cfg.center_on_bed_mm[0]} Y{cfg.center_on_bed_mm[1]}, "
        f"rotated {cfg.rotation_deg} deg  (TO VERIFY ON HARDWARE)",
        "; Printer-specific blocks come from templates marked TO VERIFY ON HARDWARE.",
        "G21 ; millimetres",
        "G90 ; absolute XYZ",
        "M83 ; relative extrusion",
        "",
        "; ---- start (template) ----",
    ]
    lines.append(_render(printer.gcode_start, bed_temp=printer.bed_temp_c).rstrip("\n"))

    pos = None
    for tool in layout.print_order:
        filament = printer.filaments[tool]
        lines += ["", f"; ---- tool T{tool} (template) ----"]
        tc = _render(printer.gcode_tool_change, tool=tool, nozzle_temp=filament.nozzle_temp_c)
        lines.append(tc.rstrip("\n"))
        lines += ["G90", "M83", f"G1 Z{_fmt(cfg.layer_height_mm + printer.z_hop_mm)} F600"]
        pos = None  # the tool change may move the head anywhere
        moves, pos = _tool_moves(layout.toolpaths(tool), layout, printer, pos)
        lines += [f"; T{tool}: {len(layout.toolpaths(tool))} paths", *moves]

    lines += ["", "; ---- end (template) ----"]
    lines.append(_render(printer.gcode_end).rstrip("\n"))
    return "\n".join(lines) + "\n"
